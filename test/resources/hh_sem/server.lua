-- A/B test: everything here must print exactly the same with and without the hitchhunter wrapper
local function out(k, ...)
    local n = select('#', ...)
    local parts = {}
    for i = 1, n do parts[i] = tostring((select(i, ...))) end
    print(('SEM %s n=%d [%s]'):format(k, n, table.concat(parts, ',')))
end

AddEventHandler('hh_sem:args', function(...) out('event-args', ...) end)
exports('multi', function(a) return a, nil, 'x' end)
exports('boom', function() error('kaboom') end)
RegisterCommand('hhsemcmd', function(src, args, raw) out('command', src, #args, args[1], args[2], raw) end, false)
local removed = AddEventHandler('hh_sem:rm', function() out('removed-handler-ran') end)
RemoveEventHandler(removed)
AddEventHandler('hh_sem:wait', function()
    Wait(100)
    out('after-wait-in-handler', 'ok')
end)
AddEventHandler('hh_sem:err', function() error('handler failure ' .. 42) end)

CreateThread(function()
    Wait(1500)
    TriggerEvent('hh_sem:args', 1, nil, 3)
    TriggerEvent('hh_sem:args')
    TriggerEvent('hh_sem:args', 'a', { b = 1 }, false)
    out('export-multi', exports.hh_sem:multi(5))
    local ok, err = pcall(function() return exports.hh_sem:boom() end)
    out('export-error', ok, (tostring(err):gsub('%s+', ' ')))
    out('export-js', exports.hh_sem:jsmulti(7))
    ExecuteCommand('hhsemcmd one two')
    TriggerEvent('hh_sem:rm')
    TriggerEvent('hh_sem:wait')
    out('ctn-nowait', Citizen.CreateThreadNow(function() end))
    out('ctn-wait', Citizen.CreateThreadNow(function() Wait(0) end))
    local p = promise.new()
    SetTimeout(10, function() p:reject('nope') end)
    local ok2, e2 = pcall(function() return Citizen.Await(p) end)
    out('await-reject', ok2, e2)
    local p2 = promise.new()
    SetTimeout(10, function() p2:resolve('yes') end)
    out('await-resolve', Citizen.Await(p2))
    local ok3, e3 = pcall(Citizen.Await, (function() local q = promise.new(); q:reject({ code = 7 }); return q end)())
    out('await-reject-table', ok3, type(e3), type(e3) == 'table' and e3.code)
    out('tce', TriggerClientEvent('hh_sem:none', -1, 1, nil, 3))
    out('tlce', TriggerLatentClientEvent('hh_sem:none', -1, 5000, 'x'))
    GlobalState.hh_sem = { a = 1, b = 'two' }
    out('statebag', GlobalState.hh_sem.a, GlobalState.hh_sem.b)
    out('json', json.encode({ 1, 2, { x = 'y' } }), json.decode('[1,2,{"x":"y"}]')[3].x)
    out('save', SaveResourceFile(GetCurrentResourceName(), 'sem.txt', 'hello', -1))
    out('load', LoadResourceFile(GetCurrentResourceName(), 'sem.txt'))
    local f = io.open('@hh_sem/sem.txt', 'r')
    out('io', f and f:read('a'))
    if f then f:close() end
    out('io-missing', io.open('@hh_sem/nope.txt', 'r'))
    out('timeout-ret', type(SetTimeout(5, function() end)))
    local tick = 0
    SetTimeout(50, function(...) tick = select('#', ...) end)
    Wait(200)
    out('timeout-args', tick)
    out('source-type', type(source))
    TriggerEvent('hh_sem:err')
    Wait(500)
    print('SEM done')
end)
